for _alias, _canonical in MODEL_CLASS_ALIASES.items():
    if _canonical in CLASS_DETAILS and _alias not in CLASS_DETAILS:
        CLASS_DETAILS[_alias] = CLASS_DETAILS[_canonical]

SUPPORTED_CROPS: List[str] = sorted(list(set([v["crop"] for v in CLASS_DETAILS.values()])))

def parse_class_name(raw_class: str) -> Dict[str, Any]:
    """Return dictionary with crop and disease display names."""
    if raw_class in CLASS_DETAILS:
        return CLASS_DETAILS[raw_class]
    
    # Try alias
    if raw_class in MODEL_CLASS_ALIASES and MODEL_CLASS_ALIASES[raw_class] in CLASS_DETAILS:
        return CLASS_DETAILS[MODEL_CLASS_ALIASES[raw_class]]
    
    # Fallback parser if custom class given
    parts = raw_class.split("___")
    crop = parts[0].replace("_", " ").strip()
    disease = parts[1].replace("_", " ").strip() if len(parts) > 1 else "Unknown"
    return {
        "crop": crop,
        "disease": disease,
        "scientific_name": "N/A",
        "severity": "Moderate",
        "category": "Unknown",
        "is_healthy": "healthy" in raw_class.lower(),
    }

